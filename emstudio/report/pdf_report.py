"""Professional PDF report generator — EMStudio's build-house deliverable pillar.

One document per analysis: title/summary, a construction or geometry drawing, result
curves, and a BOM / construction schedule — everything a parts house, wire
manufacturer, or fab supplier needs to build the design.

Built on matplotlib's PdfPages (no extra dependency; EMStudio already uses
matplotlib). Qt-free and FreeCAD-free so it runs headlessly and is unit-testable.
Two entry points today: ``litz_report`` (Litz Designer) and ``antenna_report``
(NEC2/openEMS sweeps); both share the page furniture so new analysis types slot in.
"""

from __future__ import annotations

import matplotlib

matplotlib.use("Agg", force=False)
import numpy as np  # noqa: E402
from matplotlib.backends.backend_pdf import PdfPages  # noqa: E402
from matplotlib.figure import Figure  # noqa: E402
from matplotlib.patches import Circle as MplCircle  # noqa: E402
from matplotlib.patches import Rectangle as MplRect  # noqa: E402

PAGE = (8.27, 11.69)  # A4 portrait, inches
BRAND = "EMStudio"
# the disclaimer travels on every page of every report — these documents go to
# third parties (build houses, suppliers), so the notice must go with them
from emstudio.legal import SHORT_DISCLAIMER  # noqa: E402

FOOTER = ("Generated by EMStudio — open-source RF/EM engineering for FreeCAD\n"
          + SHORT_DISCLAIMER)


# --------------------------------------------------------------------- page parts
def _new_page():
    fig = Figure(figsize=PAGE)
    fig.subplots_adjust(left=0.08, right=0.92, top=0.92, bottom=0.06)
    return fig


def _header(fig, title, subtitle, page_no, page_total):
    fig.text(0.08, 0.965, BRAND, fontsize=16, fontweight="bold", color="#2b8cff")
    fig.text(0.08, 0.945, title, fontsize=12, fontweight="bold")
    if subtitle:
        fig.text(0.08, 0.928, subtitle, fontsize=9, color="#444444")
    fig.text(0.92, 0.965, "Page {0}/{1}".format(page_no, page_total),
             fontsize=8, ha="right", color="#888888")
    fig.text(0.5, 0.008, FOOTER, fontsize=6.5, ha="center", va="bottom",
             color="#999999")
    fig.patches.append(
        MplRect((0.08, 0.925), 0.84, 0.0015, transform=fig.transFigure,
                facecolor="#2b8cff", edgecolor="none")
    )


def _table(fig, rows, y0=0.88, x0=0.10, col_w=(0.40, 0.42), title=None, fontsize=9):
    """Draw a two-column key/value table; returns the y after the last row."""
    y = y0
    if title:
        fig.text(x0, y, title, fontsize=11, fontweight="bold")
        y -= 0.028
    for k, v in rows:
        fig.text(x0, y, str(k), fontsize=fontsize, color="#333333")
        fig.text(x0 + col_w[0], y, str(v), fontsize=fontsize, fontweight="bold")
        y -= 0.024
    return y


def _multicol_table(fig, headers, data_rows, y0, x0=0.10, width=0.82, fontsize=8,
                    col_frac=None):
    """Draw a bordered multi-column table (for BOM / schedules).

    ``col_frac`` optionally gives per-column width fractions (summing to ~1); the
    default is equal columns. Column x-positions are the cumulative offsets.
    """
    ncol = len(headers)
    if col_frac is None:
        col_frac = [1.0 / ncol] * ncol
    xs = [x0]
    for f in col_frac[:-1]:
        xs.append(xs[-1] + f * width)
    y = y0
    for j, h in enumerate(headers):
        fig.text(xs[j], y, str(h), fontsize=fontsize, fontweight="bold")
    y -= 0.006
    fig.patches.append(MplRect((x0, y), width, 0.001, transform=fig.transFigure,
                               facecolor="#333333", edgecolor="none"))
    y -= 0.020
    for row in data_rows:
        for j, cell in enumerate(row):
            fig.text(xs[j], y, str(cell), fontsize=fontsize)
        y -= 0.019
    return y


# --------------------------------------------------------------------- litz report
def _draw_cross_section(ax, construction):
    from emstudio.wire import cross_section

    data = cross_section.layout_arrays(construction)
    ax.set_aspect("equal")
    mm = 1e3
    from matplotlib.collections import EllipseCollection

    max_r = data["jacket_r"] or data["od_r"]
    if data["jacket_r"] > 0:
        ax.add_patch(MplCircle((0, 0), data["jacket_r"] * mm, facecolor="#4a4a55",
                               edgecolor="#222222", lw=1.2))
        ax.add_patch(MplCircle((0, 0), data["od_r"] * mm, facecolor="#f4f0e8",
                               edgecolor="#333333", lw=0.9))
    else:
        ax.add_patch(MplCircle((0, 0), data["od_r"] * mm, fill=False,
                               edgecolor="#333333", lw=1.2))

    def _coll(centers, radius, **kw):
        if len(centers) == 0:
            return
        d = 2.0 * radius * mm
        ax.add_collection(EllipseCollection(
            widths=[d] * len(centers), heights=[d] * len(centers), angles=0,
            units="xy", offsets=centers * mm, transOffset=ax.transData, **kw))

    for centers, r, _l in data["bundles"]:
        _coll(centers, r, facecolors="none", edgecolors="#2b8cff",
              linestyles="--", linewidths=0.7)
    core_pos, core_r = data["cores"]
    for (kx, ky), kr in zip(core_pos, core_r):
        ax.add_patch(MplCircle((kx * mm, ky * mm), kr * mm, facecolor="#eeeeee",
                               edgecolor="#888888", lw=0.6, hatch="...."))
    n = len(data["strands"])
    _coll(data["strands"], data["strand_r"], facecolors="#c87533",
          edgecolors=("#7a4418" if n <= 20000 else "none"),
          linewidths=(0.3 if n <= 20000 else 0.0))
    if data["profile"] is not None:
        hw, hh = data["profile"]
        ax.add_patch(MplRect((-hw * mm, -hh * mm), 2 * hw * mm, 2 * hh * mm,
                             fill=False, edgecolor="#ff5a5f", lw=1.2, linestyle="-."))
        max_r = max(max_r, hw)
    lim = max_r * mm * 1.1
    ax.set_xlim(-lim, lim)
    ax.set_ylim(-lim, lim)
    ax.set_xlabel("mm", fontsize=8)


def litz_report(construction, path, freq_min_hz=1e3, freq_max_hz=1e6,
                i_rms=None, h_ext_per_amp=0.0, project="", author=""):
    """Write a litz construction report PDF. Returns the path."""
    from emstudio.wire import litz as _l

    spec = construction.spec_dict()
    freqs = np.logspace(np.log10(freq_min_hz), np.log10(max(freq_max_hz, freq_min_hz * 2)), 200)
    fac = np.array([construction.ac_factor(f, h_ext_per_amp) for f in freqs])
    rac = np.array([construction.rac_per_meter(f, h_ext_per_amp) for f in freqs])

    with PdfPages(path) as pdf:
        # --- page 1: summary + cross-section ---
        fig = _new_page()
        _header(fig, "Litz Cable Construction Report", construction.name, 1, 2)
        rows = [
            ("Project", project or "—"),
            ("Prepared by", author or "—"),
            ("Litz type", "Type {0} — {1}".format(spec["litz_type"], spec["type_description"])),
            ("Strand", spec["strand_diameter"]),
            ("Total strands", spec["n_strands"]),
            ("Conductor OD", "{0:.3f} mm".format(spec["outer_diameter_mm"])),
            ("Finished OD (jacket)", "{0:.3f} mm".format(spec["finished_od_mm"])),
            ("Equivalent solid", "AWG {0}".format(spec["equivalent_awg"])),
            ("DC resistance", "{0:.3f} mΩ/m".format(spec["rdc_mohm_per_m"])),
            ("Copper weight", "{0:.2f} g/m".format(spec["copper_weight_g_per_m"])),
            ("Ampacity (DC, 30 K, still air)", "{0:.0f} A".format(spec["ampacity_dc_a"])),
        ]
        _table(fig, rows, y0=0.88, title="Summary")
        ax = fig.add_axes([0.10, 0.10, 0.80, 0.42])
        _draw_cross_section(ax, construction)
        ax.set_title("Cross-section (nominal — strands migrate along the lay)", fontsize=9)
        pdf.savefig(fig)

        # --- page 2: schedule + AC curves ---
        fig = _new_page()
        _header(fig, "Construction Schedule & AC Performance", construction.name, 2, 2)
        headers = ["Level", "Members", "Lay", "Dir", "Core", "Wrap", "OD after"]

        def _wrap_label(op):
            if not op["member_wrap"] or op["member_wrap"] == "—":
                return "—"
            short = op["member_wrap"].replace("polyester", "poly.").replace(" tape", " tp")
            if op["member_wrap_mm"] == 0:
                return short
            return "{0} {1:.2f}mm".format(short, op["member_wrap_mm"])

        data_rows = []
        for op in spec["operations"]:
            data_rows.append([
                op["level"], op["count"], "{0:.1f} mm".format(op["lay_mm"]),
                op["direction"],
                ("{0:.2f} mm".format(op["core_mm"]) if op["core_mm"] > 0 else "—"),
                _wrap_label(op),
                "{0:.2f} mm".format(op["od_after_mm"]),
            ])
        y = _multicol_table(fig, headers, data_rows, 0.86,
                            col_frac=(0.09, 0.13, 0.14, 0.08, 0.16, 0.24, 0.16))
        fig.text(0.10, y - 0.01, "Jacket: {0}".format(spec["jacket"]) + (
            ", {0:.2f} mm wall".format(spec["jacket_mm"]) if spec["jacket_mm"] > 0 else ""),
            fontsize=8)

        ax1 = fig.add_axes([0.12, 0.34, 0.78, 0.22])
        ax1.semilogx(freqs / 1e3, fac, "-", lw=2)
        ax1.set_ylabel("Rac / Rdc", fontsize=8)
        ax1.grid(True, which="both", alpha=0.4)
        ax1.set_title("AC resistance vs frequency", fontsize=9)
        ax2 = fig.add_axes([0.12, 0.09, 0.78, 0.20])
        ax2.loglog(freqs / 1e3, rac * 1e3, "-", lw=2)
        ax2.set_xlabel("Frequency (kHz)", fontsize=8)
        ax2.set_ylabel("Rac (mΩ/m)", fontsize=8)
        ax2.grid(True, which="both", alpha=0.4)
        pdf.savefig(fig)

        _set_metadata(pdf, "EMStudio Litz Report — " + construction.name, author)
    return path


# ------------------------------------------------------------------ antenna report
def antenna_report(result, path, title="Antenna Analysis", geometry_png=None,
                   bom_rows=None, project="", author=""):
    """Write an antenna/S-parameter report from a SweepResult. Returns the path."""
    f_min, s11_min = result.min_s11()
    with PdfPages(path) as pdf:
        fig = _new_page()
        _header(fig, title, result.meta.get("analysis", ""), 1, 2)
        rows = [
            ("Project", project or "—"),
            ("Prepared by", author or "—"),
            ("Solver", result.meta.get("backend", "—")),
            ("Port impedance", "{0:.0f} Ω".format(result.z0)),
            ("Best match", "{0:.2f} dB @ {1:.4f} GHz".format(s11_min, f_min / 1e9)),
            ("Min VSWR", "{0:.2f}".format(float(result.vswr().min()))),
        ]
        res = result.resonances()
        if res:
            rows.append(("Resonance(s)", ", ".join("{0:.3f} GHz".format(r / 1e9) for r in res[:3])))
        ff = getattr(result, "farfield", None)
        if ff is not None:
            g, th, _ = ff.peak()
            rows.append(("Peak gain", "{0:.2f} dBi @ θ={1:.0f}°".format(g, th)))
        _table(fig, rows, y0=0.88, title="Summary")

        ax = fig.add_axes([0.12, 0.36, 0.78, 0.20])
        ax.plot(result.freq / 1e9, result.s11_db(), "-", lw=2)
        ax.axhline(-10, ls="--", lw=1, color="#888888")
        ax.set_ylabel("S11 (dB)", fontsize=8)
        ax.set_xlabel("Frequency (GHz)", fontsize=8)
        ax.grid(True, alpha=0.4)
        ax.set_title("Reflection (S11)", fontsize=9)
        ax2 = fig.add_axes([0.12, 0.09, 0.78, 0.19])
        ax2.plot(result.freq / 1e9, np.real(result.zin), "-", lw=2, label="R")
        ax2.plot(result.freq / 1e9, np.imag(result.zin), "--", lw=2, label="X")
        ax2.axhline(0, lw=0.8, color="#888888")
        ax2.set_ylabel("Zin (Ω)", fontsize=8)
        ax2.set_xlabel("Frequency (GHz)", fontsize=8)
        ax2.grid(True, alpha=0.4)
        ax2.legend(fontsize=7)
        pdf.savefig(fig)

        # --- page 2: pattern + BOM ---
        fig = _new_page()
        _header(fig, title + " — Pattern & BOM", result.meta.get("analysis", ""), 2, 2)
        if ff is not None:
            ax = fig.add_axes([0.15, 0.45, 0.7, 0.45], projection="polar")
            for phi, style in ((0.0, "-"), (90.0, "--")):
                theta, gain = ff.cut(phi)
                ax.plot(np.deg2rad(theta), gain, style, lw=2,
                        label="φ={0:.0f}°".format(phi))
                if theta.max() <= 180.0:
                    ax.plot(-np.deg2rad(theta), gain, style, lw=1, alpha=0.6)
            ax.set_theta_zero_location("N")
            g, _, _ = ff.peak()
            ax.set_rmin(g - 40.0)
            ax.set_title("Radiation pattern (dBi) @ {0:.3f} GHz".format(ff.freq / 1e9),
                         fontsize=9)
            ax.legend(loc="lower left", fontsize=7)
        else:
            fig.text(0.5, 0.6, "No far-field data (enable ComputeFarField on the solver)",
                     ha="center", fontsize=9, color="#888888")
        if bom_rows:
            _multicol_table(fig, ["Item", "Detail", "Qty/Value"], bom_rows, 0.36)
        pdf.savefig(fig)
        _set_metadata(pdf, "EMStudio " + title, author)
    return path


