def matching_report(design, path, title="Matching Network", project="",
                    author="", q_ind=None, q_cap=None):
    """Write a §7 matching-network design report (summary + predicted curves +
    component schedule + schematic). ``design`` is a
    :mod:`emstudio.system.matching` design dict. Returns the path.

    Optional ``q_ind``/``q_cap`` give component quality factors so the report's
    insertion-loss figure reflects real (lossy) parts."""
    from emstudio.system import matching as _M

    f0 = design["match_freq_hz"]
    zs = complex(design.get("z_source", complex(50.0)))
    zl = complex(design.get("z_load", complex(50.0)))
    z0 = _matching_ref_z0(design)
    with PdfPages(path) as pdf:
        # page 1: summary + predicted VSWR / return-loss curves
        fig = _new_page()
        _header(fig, title, project, 1, 2)
        y = _table(fig, _matching_summary_rows(design, q_ind, q_cap), y0=0.87,
                   title="Matching summary")
        notes = list(design.get("warnings", []) or []) + \
            list(design.get("notes", []) or [])
        if notes:
            import textwrap
            fig.text(0.10, y - 0.010, "Notes & caveats", fontsize=11,
                     fontweight="bold")
            y -= 0.040
            for w in notes:
                for ln in textwrap.wrap("- " + str(w), 96):
                    fig.text(0.10, y, ln, fontsize=7.5, color="#444444")
                    y -= 0.016
                y -= 0.003
        # predicted curves (live matplotlib axes, per the house furniture)
        span = [f0 * (0.5 + 1.0 * k / 120.0) for k in range(121)]
        ev = _M.evaluate(design.get("elements", []), zs, zl, span, z0=z0, f0_hz=f0)
        ax = fig.add_axes([0.12, 0.10, 0.76, 0.26])
        fmhz = [f / 1e6 for f in span]
        ax.plot(fmhz, ev["vswr"], color="#2b8cff", label="VSWR")
        ax.set_xlabel("Frequency (MHz)", fontsize=8)
