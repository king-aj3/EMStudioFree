def _matching_ref_z0(design):
    """The system reference the match is measured against = Re(z_source)."""
    zs = design.get("z_source", complex(50.0, 0.0))
    return design.get("z0") or (complex(zs).real if zs else 50.0)


def _matching_summary_rows(design, q_ind=None, q_cap=None):
    from emstudio.system import matching as _M

    f0 = design["match_freq_hz"]
    zs = complex(design.get("z_source", complex(50.0)))
    zl = complex(design.get("z_load", complex(50.0)))
    z0 = _matching_ref_z0(design)
    ev = _M.evaluate(design.get("elements", []), zs, zl, [f0], z0=z0, f0_hz=f0)
    il = _M.estimate_insertion_loss_db(design, q_ind=q_ind, q_cap=q_cap)
    rows = [
        ("Topology", design.get("name", design.get("kind", "?"))),
        ("Source / system Z0", "{0:.3g} ohm".format(z0)),
        ("Element (load) Z", "{0:.4g}{1:+.4g}j ohm".format(zl.real, zl.imag)),
        ("Design frequency", _fmt_freq(f0)),
    ]
    if design.get("q_network") is not None:
        rows.append(("Network Q", "{0:.3g}".format(design["q_network"])))
    if design.get("q_loaded") is not None:
        rows.append(("Loaded Q (chosen)", "{0:.3g}".format(design["q_loaded"])))
    rows += [
        ("Predicted VSWR @ f0", "{0:.3f}".format(ev["vswr"][0])),
        ("Predicted return loss @ f0", "{0:.1f} dB".format(ev["return_loss_db"][0])),
        ("Est. insertion loss",
         "{0:.3f} dB{1}".format(il, "" if (q_ind or q_cap) else " (ideal parts)")),
    ]
    return rows


