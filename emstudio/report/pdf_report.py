def _fmt_freq(f):
    if f >= 1e9:
        return "{0:.4g} GHz".format(f / 1e9)
    if f >= 1e6:
        return "{0:.4g} MHz".format(f / 1e6)
    if f >= 1e3:
        return "{0:.4g} kHz".format(f / 1e3)
    return "{0:.4g} Hz".format(f)


def _draw_axi_geometry(ax, bodies):
    """Schematic r-z cross-section, mirrored about the axis (coil vs conductor)."""
    from matplotlib.patches import Patch

    for b in bodies:
        r0, r1, z0, z1 = b["r0"], b["r1"], b["z0"], b["z1"]
        color = "#2b8cff" if b.get("is_coil") else "#c87533"
        for x in (r0, -r1):  # right side, then mirror
            ax.add_patch(MplRect((x, z0), r1 - r0, z1 - z0, facecolor=color,
                                 edgecolor="#222222", lw=0.8, alpha=0.75))
        ax.text(0.5 * (r0 + r1), z1, b["name"], fontsize=6.5, ha="center",
                va="bottom", color="#222222")
    ax.axvline(0.0, ls="--", lw=0.8, color="#888888")
    r_max = max(b["r1"] for b in bodies)
    z_lo = min(b["z0"] for b in bodies)
    z_hi = max(b["z1"] for b in bodies)
    m = 0.15 * max(2 * r_max, z_hi - z_lo) + 1e-9
    ax.set_xlim(-r_max - m, r_max + m)
    ax.set_ylim(z_lo - m, z_hi + m)
    ax.set_aspect("equal")
    ax.set_xlabel("r (mm)  — mirrored about the axis", fontsize=8)
    ax.set_ylabel("z (mm)", fontsize=8)
    ax.legend(handles=[Patch(facecolor="#2b8cff", label="coil (driven)"),
                       Patch(facecolor="#c87533", label="conductor")],
              fontsize=7, loc="upper right")


def _draw_field_map(ax, vtu_path, freq_hz, bodies):
    """|B| amplitude in the r-z plane from the solved VTU (raises if unreadable)."""
    import matplotlib.tri as mtri

    from emstudio.solvers.elmer import parser

    mesh = parser.parse_vtu(vtu_path)
    pts = mesh["points"]
    br = mesh["point_data"].get("magnetic flux density re")
    bi = mesh["point_data"].get("magnetic flux density im")
    if br is None or bi is None:
        raise ValueError("no magnetic flux density in VTU")
    # phasor amplitude of the field vector, in mT
    bmag = np.sqrt(br[:, 0] ** 2 + br[:, 1] ** 2 + bi[:, 0] ** 2 + bi[:, 1] ** 2) * 1e3
    r_max = max(b["r1"] for b in bodies) * 1.6
    z_lo = min(b["z0"] for b in bodies)
    z_hi = max(b["z1"] for b in bodies)
    zc = 0.5 * (z_lo + z_hi)
    zh = max(0.5 * (z_hi - z_lo), r_max * 0.5) * 1.4
    view = (pts[:, 0] <= r_max) & (pts[:, 1] >= zc - zh) & (pts[:, 1] <= zc + zh)
    vmax = float(np.percentile(bmag[view], 97)) if view.any() else float(bmag.max())
    vmax = max(vmax, 1e-6)
    triang = mtri.Triangulation(pts[:, 0], pts[:, 1], mesh["triangles"])
    tcf = ax.tricontourf(triang, bmag, levels=np.linspace(0, vmax, 24),
                         cmap="magma", extend="max")
    ax.figure.colorbar(tcf, ax=ax, label="|B| amplitude (mT)", shrink=0.8)
    for b in bodies:
        ax.add_patch(MplRect((b["r0"], b["z0"]), b["r1"] - b["r0"], b["z1"] - b["z0"],
                             fill=False, lw=1.0,
                             edgecolor="#66ccff" if b.get("is_coil") else "#00e0a0"))
    ax.set_xlim(0, r_max)
    ax.set_ylim(zc - zh, zc + zh)
    ax.set_aspect("equal")
    ax.set_xlabel("r (mm)", fontsize=8)
    ax.set_ylabel("z (mm)", fontsize=8)
    ax.set_title("Magnetic flux density @ {0}".format(_fmt_freq(freq_hz)), fontsize=9)


def magnetics_report(result, path, title="Magnetics Analysis", project="", author=""):
    """Write an induction-heating / WPT magnetics report PDF. Returns the path.

    Adapts to the analysis: induction runs get power / temperature / coil
    impedance; WPT runs get the L/M/k coupling table. A field map is drawn
    from the solved VTU when available (gracefully omitted otherwise).
    """
    sweeps = result.sweep_cases()
    lmat = result.inductance_matrix()
    ks = result.coupling_k()
    bodies = result.bodies
    c0 = sweeps[0] if sweeps else None
    freqs = result.freqs_hz()
    heating = result.heating_curve()
    has_curve = len(sweeps) >= 3
    n_pages = 2 + (1 if (has_curve or heating) else 0)

    with PdfPages(path) as pdf:
        # --- page 1: summary + geometry ---
        fig = _new_page()
        _header(fig, title, result.meta.get("analysis", ""), 1, n_pages)
        rows = [
            ("Project", project or "—"),
            ("Prepared by", author or "—"),
            ("Solver", "{0} ({1})".format(
                result.meta.get("backend", "Elmer"),
                "general 3-D magnetostatic FEM (WhitneyAV)"
                if result.meta.get("mode3d") else
                "axisymmetric static DC FEM" if result.meta.get("static")
                else "axisymmetric harmonic FEM")),
        ]
        if freqs:
            rows.append(("Frequency", _fmt_freq(freqs[0]) if len(freqs) == 1
                         else "{0} – {1}, {2} points".format(
                             _fmt_freq(freqs[0]), _fmt_freq(freqs[-1]), len(freqs))))
        if c0 and c0["eddy_power_w"] > 0:
            rows.append(("Total eddy/Joule power", "{0:.4g} W @ {1}".format(
                c0["eddy_power_w"], _fmt_freq(c0["freq_hz"]))))
        if c0 and (c0.get("temperature")):
            tmax = max(t["t_max"] for t in c0["temperature"].values())
            rows.append(("Peak temperature", "{0:.1f} K  ({1:.0f} °C)".format(
                tmax, tmax - 273.15)))
        for (ni, nj), k in sorted(ks.items()):
            rows.append(("Coupling k ({0} <-> {1})".format(ni, nj),
                         "{0:.4g}".format(k)))
        _table(fig, rows, y0=0.88, title="Summary")

        ax = fig.add_axes([0.12, 0.09, 0.78, 0.44])
        if bodies and all("r0" in b for b in bodies):
            _draw_axi_geometry(ax, bodies)
            ax.set_title("Axisymmetric cross-section (r–z)", fontsize=9)
        else:
            fig.delaxes(ax)
            fig.text(0.5, 0.3, "(geometry unavailable)", ha="center",
                     fontsize=9, color="#888888")
        pdf.savefig(fig)

        # --- page 2: field map + result/BOM tables ---
        fig = _new_page()
        _header(fig, title + " — Fields & Bill of Materials",
                result.meta.get("analysis", ""), 2, n_pages)
        drew_field = False
        if c0 and bodies and all("r0" in b for b in bodies):
            ax = fig.add_axes([0.14, 0.52, 0.72, 0.33])
            try:
                _draw_field_map(ax, c0["vtu"], c0["freq_hz"], bodies)
                drew_field = True
            except Exception:  # noqa: BLE001 — field map is best-effort
                fig.delaxes(ax)
        if not drew_field:
            fig.text(0.5, 0.70, "(field map unavailable — VTU not found)",
                     ha="center", fontsize=9, color="#888888")

        # bodies: materials + losses + temperature.
        # Per-body power is the nodal decomposition RESCALED so it sums to the
        # field-integrated total (c0["eddy_power_w"]) — the nodal integral gets
        # the split between bodies right but is a few % low in absolute scale
        # (skin-peak under-resolution), so this keeps the breakdown consistent
        # with the headline total instead of leaking a few W on a lone body.
        headers = ["Body", "Role", "σ [MS/m]", "μr", "k [W/mK]", "P [W]", "Tmax [K]"]
        power = c0["body_power_w"] if c0 else {}
        nodal_total = sum(power.values())
        pscale = (c0["eddy_power_w"] / nodal_total) if (c0 and nodal_total > 0) else 1.0
        temps = (c0.get("temperature") if c0 else None) or {}
        data_rows = []
        for b in bodies:
            t = temps.get(b["name"], {})
            p_disp = power.get(b["name"], 0.0) * pscale
            data_rows.append([
                b["name"],
                "coil" if b.get("is_coil") else "conductor",
                "{0:.3g}".format(b.get("sigma", 0.0) / 1e6) if b.get("sigma", 0) else "—",
                "{0:.3g}".format(b.get("mu_r", 1.0)),
                "{0:.3g}".format(b["k_th"]) if b.get("k_th") else "—",
                "{0:.4g}".format(p_disp) if power.get(b["name"]) else "—",
                "{0:.1f}".format(t["t_max"]) if t else "—",
            ])
        y = _multicol_table(fig, headers, data_rows, 0.48,
                            col_frac=(0.22, 0.16, 0.14, 0.10, 0.14, 0.12, 0.12))

        # coils: electrical (turns / current / L / reflected R at the first freq).
        # L is the true self-inductance from the coupling extraction when it ran
        # (WPT); otherwise the in-situ effective inductance from the all-coils
        # sweep (induction — the coil's inductance with the workpiece present).
        # Reflected R (eddy loss referred to the coil) is shown only when real.
        if result.coils and c0:
            y -= 0.02
            cheaders = ["Coil", "Turns", "I_peak [A]", "L [µH]", "R_refl [mΩ]"]
            crows = []
            for coil in result.coils:
                name = coil["name"]
                _, ls, rs = result.coil_impedance(name)
                # prefer the self-inductance from the coupling extraction (WPT);
                # else the operating-point L_eff (may be NaN for an undriven coil)
                l_h = lmat[(name, name)] if (name, name) in lmat else ls[0]
                l_txt = "{0:.4g}".format(l_h * 1e6) if not np.isnan(l_h) else "—"
                r_txt = ("{0:.4g}".format(rs[0] * 1e3)
                         if not np.isnan(rs[0]) and abs(rs[0]) > 1e-6 else "—")
                crows.append([
                    name, coil.get("turns", "—"),
                    "{0:.4g}".format(coil.get("current_a", 0.0)),
                    l_txt, r_txt,
                ])
            y = _multicol_table(fig, cheaders, crows, y,
                                col_frac=(0.24, 0.16, 0.20, 0.20, 0.20))

        # coupling matrix (WPT)
        if lmat:
            y -= 0.02
            mheaders = ["Pair", "L1 [µH]", "L2 [µH]", "M [µH]", "k"]
            mrows = []
            for (ni, nj), k in sorted(ks.items()):
                m_h = 0.5 * (lmat[(ni, nj)] + lmat[(nj, ni)])
                mrows.append([
                    "{0} <-> {1}".format(ni, nj),
                    "{0:.4g}".format(lmat[(ni, ni)] * 1e6),
                    "{0:.4g}".format(lmat[(nj, nj)] * 1e6),
                    "{0:.4g}".format(m_h * 1e6),
                    "{0:.4g}".format(k),
                ])
            _multicol_table(fig, mheaders, mrows, y,
                            col_frac=(0.28, 0.18, 0.18, 0.18, 0.18))
        pdf.savefig(fig)

        # --- page 3 (optional): heating curve and/or frequency-sweep curves ---
        if has_curve or heating:
            fig = _new_page()
            sub = "Heating Curve" if heating else "Frequency Sweep"
            _header(fig, title + " — " + sub, result.meta.get("analysis", ""),
                    3, n_pages)
            if heating:
                t, temp = heating
                ax0 = fig.add_axes([0.12, 0.55, 0.78, 0.34])
                ax0.plot(np.array(t), np.array(temp) - 273.15, "-o", lw=2, ms=3)
                ax0.set_xlabel("time (s)", fontsize=8)
                ax0.set_ylabel("max temperature (°C)", fontsize=8)
                ax0.grid(True, alpha=0.4)
                ax0.set_title("Transient heating curve (workpiece hottest point)",
                              fontsize=9)
            elif has_curve:
                fhz = np.array(result.freqs_hz())
                ax1 = fig.add_axes([0.12, 0.55, 0.78, 0.34])
                ax1.semilogx(fhz, np.array(result.eddy_power_w()), "-o", lw=2, ms=3)
                ax1.set_ylabel("Eddy/Joule power (W)", fontsize=8)
                ax1.grid(True, which="both", alpha=0.4)
                ax1.set_title("Dissipated power vs frequency", fontsize=9)
                if result.coils:
                    ax2 = fig.add_axes([0.12, 0.10, 0.78, 0.34])
                    for coil in result.coils:
                        cf, ls, _ = result.coil_impedance(coil["name"])
