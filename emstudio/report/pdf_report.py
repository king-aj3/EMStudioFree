def _draw_element_schematic(ax, family, design):
    """Simple dimensioned build sketch per family (report-grade, not the
    dialog's interactive one)."""
    d = design
    ax.set_aspect("equal")
    ax.axis("off")
    if family in ("yagi", "lpda"):
        els = d.get("elements", [])
        if not els:
            return
        xs = [e["position_m"] for e in els]
        maxlen = max(e["length_m"] for e in els)
        span = max(max(xs) - min(xs), 1e-9)
        ax.plot([min(xs), max(xs)], [0, 0], "-", color="#666666", lw=2)
        key = "driven" if family == "yagi" else "fed"
        for e in els:
            half = e["length_m"] / 2.0
            color = "#d33333" if e.get("kind") == key else "#c87533"
            ax.plot([e["position_m"], e["position_m"]], [-half, half], "-",
                    color=color, lw=2)
            if e.get("kind") == key:
                ax.plot([e["position_m"]], [0], "o", color="#d33333", ms=4)
        ax.annotate("", xy=(max(xs), -maxlen * 0.62),
                    xytext=(min(xs), -maxlen * 0.62),
                    arrowprops=dict(arrowstyle="<->", color="#2b8cff"))
        ax.text((min(xs) + max(xs)) / 2.0, -maxlen * 0.75,
                "boom {0:.4g} m".format(d.get("boom_length_m", span)),
                ha="center", color="#2b8cff", fontsize=8)
        ax.set_xlim(min(xs) - 0.08 * span, max(xs) + 0.12 * span)
        ax.set_ylim(-maxlen * 0.95, maxlen * 0.72)
        return
    if family == "patch":
        w = d.get("width_m", 0.0) * 1e3
        length = d.get("length_m", 0.0) * 1e3
        off = d.get("feed_offset_m", 0.0) * 1e3
        ax.add_patch(MplRect((-length / 2, -w / 2), length, w,
                             facecolor="#c87533", alpha=0.6,
                             edgecolor="#7a4a1e"))
        ax.plot([off], [0], "o", color="#d33333", ms=5)
        ax.annotate("", xy=(length / 2, -w * 0.62), xytext=(-length / 2, -w * 0.62),
                    arrowprops=dict(arrowstyle="<->", color="#2b8cff"))
        ax.text(0, -w * 0.72, "L = {0:.2f} mm (resonant)".format(length),
                ha="center", fontsize=8, color="#2b8cff")
        ax.annotate("", xy=(length * 0.62, w / 2), xytext=(length * 0.62, -w / 2),
                    arrowprops=dict(arrowstyle="<->", color="#2b8cff"))
        ax.text(length * 0.72, 0, "W = {0:.2f} mm".format(w), rotation=90,
                va="center", fontsize=8, color="#2b8cff")
        ax.text(off, w * 0.10, "feed", fontsize=7, ha="center", color="#d33333")
        ax.set_xlim(-length * 0.85, length * 0.95)
        ax.set_ylim(-w * 0.9, w * 0.8)
        return
    # wire family: a vertical element with a length dimension. Dipole/folded
    # are center-fed free-standing; monopole AND the lambda-fraction
    # verticals are BASE-fed over ground (the dialog sketch convention)
    length = d.get("length_m", 0.0) or 1e-9
    grounded = d.get("kind") not in ("dipole", "folded")
    ax.plot([0, 0], [0, length], "-", color="#c87533", lw=3)
    feed_y = 0.0 if grounded else length / 2.0
    ax.plot([0], [feed_y], "o", color="#d33333", ms=5)
    ax.annotate("", xy=(length * 0.12, length), xytext=(length * 0.12, 0),
                arrowprops=dict(arrowstyle="<->", color="#2b8cff"))
    ax.text(length * 0.16, length / 2.0,
            "{0:.4f} m".format(length), rotation=90, va="center",
            fontsize=8, color="#2b8cff")
    if grounded:
        ax.plot([-length * 0.15, length * 0.3], [0, 0], "-", color="#555555",
                lw=1.5)
        ax.text(length * 0.22, -length * 0.05, "ground", fontsize=7,
                color="#555555")
    ax.set_xlim(-length * 0.3, length * 0.5)
    ax.set_ylim(-length * 0.12, length * 1.1)


def element_report(design, path, family=None, title="Element Design",
                   project="", author=""):
    """Write an Element Designer build report (summary + schedule + sketch).

    ``design`` is an engine design dict (``wire_elements``/``yagi``/
    ``patch_tl``/``lpda``); ``family`` overrides/supplies ``design['family']``
    (the wire engines don't tag one). Returns the path.
    """
    fam = family or design.get("family") or "wire"
    with PdfPages(path) as pdf:
        # page 1: summary
        fig = _new_page()
        _header(fig, title, project, 1, 2)
        y = _table(fig, _element_summary_rows(fam, design), y0=0.87,
                   title="Design summary")
        warnings = list(design.get("warnings", []) or [])
        if warnings:
            fig.text(0.10, y - 0.012, "Notes & caveats", fontsize=11,
                     fontweight="bold")
            y -= 0.042
            import textwrap

            for w in warnings:
                for ln in textwrap.wrap("- " + str(w), 96):
                    fig.text(0.10, y, ln, fontsize=7.5, color="#444444")
                    y -= 0.016
                y -= 0.004
        src = design.get("source_note", "")
        if src:
            import textwrap

            y -= 0.010
            for ln in textwrap.wrap("Source: " + str(src), 100):
                fig.text(0.10, y, ln, fontsize=7, color="#777777")
                y -= 0.014
        pdf.savefig(fig)

        # page 2: build sketch + schedule. The schedule area fits ~22 rows;
        # longer schedules (an LPDA can reach n_max = 40 elements) split into
        # two side-by-side blocks so no row ever slides off the page.
        fig = _new_page()
        _header(fig, title, project, 2, 2)
        ax = fig.add_axes([0.10, 0.52, 0.80, 0.36])
        _draw_element_schematic(ax, fam, design)
        headers, rows, frac = _element_schedule(fam, design)
        max_rows = 22
        if len(rows) <= max_rows:
            _multicol_table(fig, headers, rows, y0=0.46, col_frac=frac)
        else:
            split = (len(rows) + 1) // 2
            if split > max_rows:  # hard guard (>44 rows cannot happen today)
                rows = rows[:2 * max_rows - 1] + [
                    tuple(["…"] * len(headers))]
                split = max_rows
            _multicol_table(fig, headers, rows[:split], y0=0.46,
                            x0=0.06, width=0.42, col_frac=frac)
            _multicol_table(fig, headers, rows[split:], y0=0.46,
                            x0=0.54, width=0.42, col_frac=frac)
        pdf.savefig(fig)

        _set_metadata(pdf, "EMStudio " + title, author)
    return path


def _set_metadata(pdf, title, author):
    d = pdf.infodict()
    d["Title"] = title
    d["Author"] = author or "EMStudio"
    d["Creator"] = "EMStudio (FreeCAD workbench)"


